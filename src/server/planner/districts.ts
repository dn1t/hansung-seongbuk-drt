export function nearestDistrict(point: Point) {
  let best = SEOUL_DISTRICTS[0];
  for (const entry of SEOUL_DISTRICTS) {
    if (distance(point, { lat: entry[1], lng: entry[2] }) < distance(point, { lat: best[1], lng: best[2] }))
      best = entry;
  }
  return best[0];
}
