// Generates src/radix-colors.css: Radix color scales as Tailwind theme colors.
//
// Each color is `light-dark(<light>, <dark>)`, so it follows `color-scheme`
// (system preference by default) without any `dark:` variants.
// Tailwind only emits theme variables that are used, so unused palettes
// cost nothing. Trim PALETTES only to keep autocomplete tidy.
//
// Run: pnpm generate:colors

import { writeFileSync } from "node:fs";
import * as radix from "@radix-ui/colors";

const PALETTES = [
  // grays
  "gray",
  "mauve",
  "slate",
  "sage",
  "olive",
  "sand",
  // colors
  "tomato",
  "red",
  "ruby",
  "crimson",
  "pink",
  "plum",
  "purple",
  "violet",
  "iris",
  "indigo",
  "blue",
  "cyan",
  "teal",
  "jade",
  "green",
  "grass",
  "bronze",
  "gold",
  "brown",
  "orange",
  "amber",
  "yellow",
  "lime",
  "mint",
  "sky",
] as const;

// Also adds the alpha scales (steps a1–a12).
const INCLUDE_ALPHA = true;

const OUT = new URL("../src/radix-colors.css", import.meta.url);

type Scale = Record<string, string>;
const scales = radix as unknown as Record<string, Scale>;

function steps(scale: Scale) {
  return Object.values(scale); // steps 1–12, in order
}

function lines(name: string, light: Scale, dark: Scale, suffix = "") {
  const l = steps(light);
  const d = steps(dark);
  return l.map((value, i) => `  --color-${name}-${suffix}${i + 1}: light-dark(${value}, ${d[i]});`);
}

const out = [
  "/* Generated by scripts/radix-colors.ts. Do not edit. */",
  "@theme {",
  "  --color-*: initial;",
  "  --color-black: #000;",
  "  --color-white: #fff;",
];

if (INCLUDE_ALPHA) {
  for (const name of ["black", "white"]) {
    steps(scales[`${name}A`]).forEach((value, i) => out.push(`  --color-${name}-a${i + 1}: ${value};`));
  }
}

for (const name of PALETTES) {
  out.push("", ...lines(name, scales[name], scales[`${name}Dark`]));
  if (INCLUDE_ALPHA) out.push(...lines(name, scales[`${name}A`], scales[`${name}DarkA`], "a"));
}

out.push("}", "");
writeFileSync(OUT, out.join("\n"));
console.log(`wrote ${OUT.pathname} (${PALETTES.length} palettes)`);
